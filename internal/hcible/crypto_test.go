package hcible

import "testing"

// Test vectors from Linux kernel net/bluetooth/smp.c test_c1()/test_s1(),
// which are themselves the Bluetooth Core Spec Vol 3 Part H Appendix C
// sample data.
func TestSMPC1(t *testing.T) {
	k := [16]byte{}
	r := [16]byte{0xe0, 0x2e, 0x70, 0xc6, 0x4e, 0x27, 0x88, 0x63, 0x0e, 0x6f, 0xad, 0x56, 0x21, 0xd5, 0x83, 0x57}
	preq := [7]byte{0x01, 0x01, 0x00, 0x00, 0x10, 0x07, 0x07}
	pres := [7]byte{0x02, 0x03, 0x00, 0x00, 0x08, 0x00, 0x05}
	iat := byte(0x01)
	ia := [6]byte{0xa6, 0xa5, 0xa4, 0xa3, 0xa2, 0xa1}
	rat := byte(0x00)
	ra := [6]byte{0xb6, 0xb5, 0xb4, 0xb3, 0xb2, 0xb1}
	want := [16]byte{0x86, 0x3b, 0xf1, 0xbe, 0xc5, 0x4d, 0xa7, 0xd2, 0xea, 0x88, 0x89, 0x87, 0xef, 0x3f, 0x1e, 0x1e}

	got := smpC1(k, r, preq, pres, iat, ia, rat, ra)
	if got != want {
		t.Fatalf("smpC1 = %x, want %x", got, want)
	}
}

func TestSMPS1(t *testing.T) {
	k := [16]byte{}
	r1 := [16]byte{0x88, 0x77, 0x66, 0x55, 0x44, 0x33, 0x22, 0x11}
	r2 := [16]byte{0x00, 0xff, 0xee, 0xdd, 0xcc, 0xbb, 0xaa, 0x99}
	want := [16]byte{0x62, 0xa0, 0x6d, 0x79, 0xae, 0x16, 0x42, 0x5b, 0x9b, 0xf4, 0xb0, 0xe8, 0xf0, 0xe1, 0x1f, 0x9a}

	got := smpS1(k, r1, r2)
	if got != want {
		t.Fatalf("smpS1 = %x, want %x", got, want)
	}
}
